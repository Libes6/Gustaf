// Claude Code session files: ~/.claude/projects/<encoded project>/<session>.jsonl, one JSON object per line.
// Lines used: `user` / `assistant` (message.content is a string or a list of text / tool_use / tool_result / image /
// thinking blocks), `custom-title`, `ai-title` and `summary` for the title. Everything else (queue operations, file
// history snapshots, hooks, attachments, ...) is skipped, as are sub-agent (`isSidechain`), `isMeta` and compaction
// summary lines. One assistant turn is written as several lines sharing `message.id`; they are merged into one message.
// Rewinds create branches (`parentUuid`); the file order is kept, so abandoned branches stay in the transcript.
import type { Part } from "../../providers/types.ts";
import { IMAGE_OMITTED } from "../exportChats.ts";
import {
  LIMITS,
  capMessages,
  cleanArgs,
  cleanText,
  eachLine,
  outputText,
  pairTools,
  parseLine,
  projectOf,
  rec,
  str,
  titleFrom,
  toMs,
  type ImportedChat,
  type ImportedMessage,
} from "./common.ts";

/** `<command-name>/x</command-name>` wrappers become the slash command text; other harness wrappers disappear. */
export function claudeUserText(raw: string): string {
  const name = /<command-name>([\s\S]*?)<\/command-name>/.exec(raw)?.[1].trim();
  if (name) {
    const args = /<command-args>([\s\S]*?)<\/command-args>/.exec(raw)?.[1].trim();
    return args ? `${name} ${args}` : name;
  }
  return raw
    .replace(/<(system-reminder|local-command-stdout|local-command-stderr|local-command-caveat)>[\s\S]*?<\/\1>/g, "")
    .replace(/^\s*Caveat: The messages below were generated by the user while running local commands[\s\S]*$/, "")
    .replace(/^\s*\[Request interrupted by user[^\]]*\]\s*$/, "")
    .trim();
}

type Block = Record<string, any>;

export function parseClaudeSession(text: string, fallbackId = ""): ImportedChat | null {
  let skippedLines = 0;
  let sessionId = "";
  let cwd: unknown;
  let title = "";
  let aiTitle = "";
  let summary = "";
  let firstUser = "";
  let createdAt: number | undefined;
  let updatedAt: number | undefined;
  const messages: ImportedMessage[] = [];
  const toolNames = new Map<string, string>();
  let lastAssistant: { id: string; msg: ImportedMessage } | null = null;

  const onLine = (line: string) => {
    const o = parseLine(line);
    if (!o) {
      skippedLines++;
      return;
    }
    switch (o.type) {
      case "custom-title":
        if (str(o.customTitle) && o.customTitle.trim()) title = titleFrom(o.customTitle);
        return;
      case "ai-title":
        if (str(o.aiTitle) && o.aiTitle.trim()) aiTitle = titleFrom(o.aiTitle);
        return;
      case "summary":
        if (!summary && str(o.summary) && o.summary.trim()) summary = titleFrom(o.summary);
        return;
      case "user":
      case "assistant":
        break;
      default:
        return;
    }
    if (
      o.isSidechain === true ||
      o.isMeta === true ||
      o.isCompactSummary === true ||
      o.isVisibleInTranscriptOnly === true
    )
      return;
    if (!rec(o.message)) return;
    if (!sessionId && str(o.sessionId) && o.sessionId) sessionId = o.sessionId;
    if (cwd === undefined && str(o.cwd) && o.cwd) cwd = o.cwd;
    const at = toMs(o.timestamp);
    if (at) {
      createdAt = Math.min(createdAt ?? at, at);
      updatedAt = Math.max(updatedAt ?? at, at);
    }
    const content: unknown = o.message.content;
    const blocks: Block[] = Array.isArray(content)
      ? content.filter(rec)
      : str(content)
        ? [{ type: "text", text: content }]
        : [];

    if (o.type === "assistant") {
      const parts: Part[] = [];
      for (const b of blocks) {
        if (b.type === "text" && str(b.text) && b.text.trim()) parts.push({ type: "text", text: cleanText(b.text) });
        else if (b.type === "tool_use" && str(b.id) && str(b.name)) {
          toolNames.set(b.id, b.name);
          parts.push({ type: "tool_call", id: b.id, name: b.name, args: cleanArgs(rec(b.input) ? b.input : {}) });
        }
      }
      if (!parts.length) return;
      const mid = str(o.message.id) ? o.message.id : "";
      if (lastAssistant && mid && lastAssistant.id === mid) {
        lastAssistant.msg.parts.push(...parts);
        return;
      }
      const model =
        str(o.message.model) && !o.message.model.startsWith("<") ? o.message.model.slice(0, 200) : undefined;
      const msg: ImportedMessage = {
        role: "assistant",
        parts,
        createdAt: at,
        meta: { imported: "claude-code", ...(model ? { model } : {}) },
      };
      messages.push(msg);
      lastAssistant = { id: mid, msg };
      return;
    }

    // user line: tool results first, then whatever the user typed
    lastAssistant = null;
    const results: Part[] = [];
    const userParts: Part[] = [];
    for (const b of blocks) {
      if (b.type === "tool_result" && str(b.tool_use_id)) {
        results.push({
          type: "tool_result",
          id: b.tool_use_id,
          name: toolNames.get(b.tool_use_id) ?? "",
          output: cleanText(outputText(b.content), LIMITS.output),
          ...(b.is_error === true ? { isError: true } : {}),
        });
      } else if (b.type === "text" && str(b.text)) {
        const t = claudeUserText(b.text);
        if (t) userParts.push({ type: "text", text: cleanText(t) });
      } else if (b.type === "image") userParts.push({ type: "text", text: IMAGE_OMITTED });
    }
    if (results.length) messages.push({ role: "tool", parts: results, createdAt: at });
    if (userParts.length) {
      if (!firstUser) firstUser = userParts.map((p) => (p.type === "text" ? p.text : "")).join(" ");
      messages.push({ role: "user", parts: userParts, createdAt: at, meta: { imported: "claude-code" } });
    }
  };
  eachLine(text, onLine, () => skippedLines++);

  const { messages: kept, clipped } = capMessages(pairTools(messages));
  if (!kept.some((m) => m.role === "user" || m.role === "assistant")) return null;
  const id = sessionId || fallbackId;
  if (!id) return null;
  return {
    source: "claude-code",
    sourceId: id,
    title: title || aiTitle || summary || titleFrom(firstUser) || "Untitled",
    createdAt,
    updatedAt,
    project: projectOf(cwd),
    messages: kept,
    skippedLines,
    clipped,
  };
}
